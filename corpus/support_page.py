"""Generates docs/SUPPORT.md from the corpus cases and KNOWN_GAPS.md.

Usage: `python -m corpus.support_page` writes the page; `--check` fails if stale.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import Counter
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import ClassVar

from corpus import test_functions, test_methods, test_ordering, test_traps
from corpus.gaps import REGISTRY_PATH
from corpus.harness import Case

PAGE_PATH = Path(__file__).resolve().parent.parent / "docs" / "SUPPORT.md"
SEVERITY_ROW = re.compile(r"^\| ((?:GAP|ORDER)-\d{3}) \| (\w+) \|", re.MULTILINE)
CLIENT_SEVERITY = "client"
CLIENT_GAP_PREFIX = "ADOPT-"
MATCHES = "matches Spark"
EXIT_STALE = 1


@dataclass(frozen=True)
class Section:
    """One corpus module rendered as one table."""

    title: str
    module: ModuleType
    what: str


@dataclass(frozen=True)
class SupportRow:
    """One case as the support page shows it."""

    case: Case
    severities: dict[str, str]

    @property
    def status(self) -> str:
        if self.case.gap is None:
            return MATCHES
        gap_id = self.case.gap.gap_id
        is_client_gap = gap_id.startswith(CLIENT_GAP_PREFIX)
        severity = CLIENT_SEVERITY if is_client_gap else self.severities[gap_id]
        return f"differs: {gap_id} ({severity})"

    def render(self) -> str:
        return f"| `{self.case.name}` | {self.status} |"


class SupportPage:
    """Renders the page and compares it with the committed copy."""

    SECTIONS: ClassVar[tuple[Section, ...]] = (
        Section("Functions", test_functions, "the `F.*` functions lakehouse code uses"),
        Section("DataFrame methods and actions", test_methods, "DataFrame API calls"),
        Section("Semantic traps", test_traps, "the rules where engines usually differ"),
        Section("Row order", test_ordering, "guaranteed and accidental row order"),
    )
    HEADER: ClassVar[str] = (
        "# Support\n\n"
        "Generated by `python -m corpus.support_page` from the corpus and "
        "`KNOWN_GAPS.md`. Do not edit by hand.\n\n"
        "Each row is a corpus case that runs on real Spark and on Sail. "
        "*matches Spark* means Sail gives the same result as Spark, compared the way "
        "`assertDataFrameEqual` compares by default. Severity: *silent* gaps change "
        "results without an error, *loud* gaps raise, *schema* gaps change types or "
        "flags only, *client* gaps come from the Spark Connect client.\n"
    )

    def __init__(self) -> None:
        self._severities = dict(SEVERITY_ROW.findall(REGISTRY_PATH.read_text()))

    def render(self) -> str:
        parts = [self.HEADER, self._summary()]
        parts.extend(self._section(section) for section in self.SECTIONS)
        return "\n".join(parts)

    def _rows(self, section: Section) -> list[SupportRow]:
        cases: list[Case] = section.module.ALL_CASES
        return [SupportRow(case, self._severities) for case in cases]

    def _summary(self) -> str:
        lines = ["| Area | Cases | Match Spark | Differ |", "|---|---|---|---|"]
        for section in self.SECTIONS:
            statuses = Counter(row.status == MATCHES for row in self._rows(section))
            total = statuses[True] + statuses[False]
            lines.append(
                f"| {section.title} | {total} | {statuses[True]} | {statuses[False]} |"
            )
        return "\n".join(lines) + "\n"

    def _section(self, section: Section) -> str:
        rows = [row.render() for row in self._rows(section)]
        table = "\n".join(["| Case | Status on Sail |", "|---|---|", *rows])
        return f"## {section.title}\n\nCovers {section.what}.\n\n{table}\n"


class SupportPageCli:
    """Writes the page, or with --check reports whether the committed page is stale."""

    def run(self, argv: list[str]) -> int:
        parser = argparse.ArgumentParser(description=__doc__)
        parser.add_argument("--check", action="store_true")
        args = parser.parse_args(argv)
        rendered = SupportPage().render()
        if not args.check:
            PAGE_PATH.parent.mkdir(parents=True, exist_ok=True)
            PAGE_PATH.write_text(rendered)
            return 0
        is_current = PAGE_PATH.exists() and PAGE_PATH.read_text() == rendered
        if not is_current:
            print(f"{PAGE_PATH} is stale; run python -m corpus.support_page")
            return EXIT_STALE
        return 0


if __name__ == "__main__":
    sys.exit(SupportPageCli().run(sys.argv[1:]))
